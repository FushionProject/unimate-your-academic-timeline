import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const root = process.cwd();
const source = path.join(root, "browser-companion");
const configPath = path.join(source, "config.local.js");
const manifest = JSON.parse(fs.readFileSync(path.join(source, "manifest.json"), "utf8"));
if (
  !/^\d+(?:\.\d+){0,3}$/.test(String(manifest.version)) ||
  String(manifest.version)
    .split(".")
    .some((part) => Number(part) > 65535)
) {
  throw new Error("Companion manifest must declare a valid numeric Chrome extension version.");
}

if (!fs.existsSync(configPath)) {
  throw new Error("Run npm run companion:configure with production settings before packaging.");
}

const configText = fs.readFileSync(configPath, "utf8");
// Accept only the generator's four literal fields, never executable JavaScript.
// Anchoring the complete file rejects duplicate fields, overrides, and trailing code.
const jsonString = String.raw`"(?:[^"\\\u0000-\u001f]|\\(?:["\\/bfnrt]|u[\da-fA-F]{4}))*"`;
const configPattern = new RegExp(
  String.raw`^\s*(?:// Generated by npm run companion:configure\. Public client configuration only\.\r?\n\s*)?self\.UNIMATE_COMPANION_CONFIG\s*=\s*\{\s*SUPABASE_URL:\s*(${jsonString})\s*,\s*SUPABASE_ANON_KEY:\s*(${jsonString})\s*,\s*UNIMATE_API_URL:\s*(${jsonString})\s*,\s*COMPANION_DEBUG:\s*(true|false)\s*,?\s*\};\s*$`,
);
const fields = configPattern.exec(configText);
if (!fields) {
  throw new Error(
    "Invalid Companion configuration structure. Regenerate with npm run companion:configure; extra fields or executable code are not permitted.",
  );
}
const config = {
  SUPABASE_URL: JSON.parse(fields[1]),
  SUPABASE_ANON_KEY: JSON.parse(fields[2]),
  UNIMATE_API_URL: JSON.parse(fields[3]),
  COMPANION_DEBUG: fields[4] === "true",
};
const validatedValues = JSON.stringify(config);
for (const [label, value] of [
  ["UniMate API", config.UNIMATE_API_URL],
  ["Supabase", config.SUPABASE_URL],
]) {
  if (!value) throw new Error(`${label} URL is missing from generated Companion configuration.`);
  const url = new URL(value);
  if (
    url.protocol !== "https:" ||
    ["localhost", "127.0.0.1", "[::1]", "0.0.0.0"].includes(url.hostname) ||
    url.hostname.endsWith(".localhost") ||
    url.username ||
    url.password ||
    url.pathname !== "/" ||
    url.search ||
    url.hash
  ) {
    throw new Error(`${label} must use a non-local HTTPS origin for Store packaging.`);
  }
}
if (config.COMPANION_DEBUG) {
  throw new Error("Disable Companion debug mode before Store packaging.");
}
if (
  /(?:sk|rk)_(?:test|live)_[A-Za-z0-9]+|sk-(?:proj-|svcacct-)?[A-Za-z0-9_-]+|sb_secret_[A-Za-z0-9_-]+|whsec_[A-Za-z0-9]+|service_role/i.test(
    validatedValues,
  )
) {
  throw new Error("Secret-like content detected in Companion configuration.");
}
const anonKey = config.SUPABASE_ANON_KEY;
if (!anonKey || /YOUR_|PLACEHOLDER/i.test(validatedValues)) {
  throw new Error("Replace placeholder Companion configuration before Store packaging.");
}
if (anonKey.split(".").length === 3) {
  if (anonKey.split(".").some((part) => !/^[A-Za-z0-9_-]+$/.test(part)))
    throw new Error("The Companion public client key is malformed.");
  let role;
  try {
    role = JSON.parse(Buffer.from(anonKey.split(".")[1], "base64url").toString("utf8")).role;
  } catch {
    throw new Error("The Companion public client key is malformed.");
  }
  if (role !== "anon")
    throw new Error(
      "Secret-like content detected in Companion configuration: only an anon JWT or public publishable key is permitted.",
    );
} else if (!/^sb_publishable_[A-Za-z0-9_-]+$/.test(anonKey)) {
  throw new Error("The Companion requires a public Supabase publishable key or anon JWT.");
}

const stage = fs.mkdtempSync(path.join(os.tmpdir(), "unimate-companion-"));
const packageRoot = path.join(stage, "unimate-browser-companion");
const packageFiles = [
  "manifest.json",
  "background.js",
  "content.js",
  "context-extractor.js",
  "signin.html",
  "signin.js",
  "signin.css",
  "config.local.js",
  "assets/mascot.png",
  ...[16, 32, 48, 128].map((size) => `assets/icons/icon${size}.png`),
];
try {
  fs.mkdirSync(path.join(packageRoot, "assets", "icons"), { recursive: true });
  for (const file of packageFiles) {
    if (file === "config.local.js") {
      // Ship only the values we validated, not the original source text.
      fs.writeFileSync(
        path.join(packageRoot, file),
        `self.UNIMATE_COMPANION_CONFIG = ${JSON.stringify(config, null, 2)};\n`,
      );
    } else {
      fs.copyFileSync(path.join(source, file), path.join(packageRoot, file));
    }
  }
  const stagedArchive = path.join(stage, "companion.zip");
  // Store uploads require manifest.json at the archive root. Explicit filenames
  // also prevent a future unrelated file in the staging folder being shipped.
  execFileSync("zip", ["-q", stagedArchive, ...packageFiles], { cwd: packageRoot });
  const entries = execFileSync("unzip", ["-Z1", stagedArchive], { encoding: "utf8" })
    .trim()
    .split("\n");
  const forbidden = entries.filter((entry) =>
    /(?:tests?|reports?|\.DS_Store|\.env|README|\.md$|localhost)/i.test(entry),
  );
  if (
    forbidden.length ||
    entries.length !== packageFiles.length ||
    packageFiles.some((file) => !entries.includes(file))
  ) {
    throw new Error("Unexpected Store package entries or missing root manifest.");
  }
  const archivedManifest = JSON.parse(
    execFileSync("unzip", ["-p", stagedArchive, "manifest.json"], { encoding: "utf8" }),
  );
  if (archivedManifest.version !== manifest.version)
    throw new Error("Packaged manifest does not match the release version.");
  const releaseDir = path.join(root, "release-artifacts");
  fs.mkdirSync(releaseDir, { recursive: true });
  const output = path.join(releaseDir, `unimate-browser-companion-${manifest.version}.zip`);
  // Keep the previous release intact until the replacement has been validated.
  fs.copyFileSync(stagedArchive, `${output}.pending`);
  fs.renameSync(`${output}.pending`, output);
  console.log(
    `Created ${path.relative(root, output)} with ${entries.length} entries and manifest.json at the root.`,
  );
} finally {
  fs.rmSync(stage, { recursive: true, force: true });
}
