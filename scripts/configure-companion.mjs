import fs from "node:fs";
import path from "node:path";
import {
  isPublicCompanionOrigin,
  isDevelopmentCompanionOrigin,
} from "./companion-config-policy.mjs";

const root = process.cwd();
const envPath = path.join(root, ".env.local");
const outputPath = path.join(root, "browser-companion", "config.local.js");

function parseEnv(text) {
  const values = {};
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const match = line.match(/^(?:export\s+)?([A-Z0-9_]+)\s*=\s*(.*)$/);
    if (!match) continue;
    let value = match[2].trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    values[match[1]] = value;
  }
  return values;
}

const env = fs.existsSync(envPath) ? parseEnv(fs.readFileSync(envPath, "utf8")) : process.env;
const config = {
  SUPABASE_URL: env.VITE_SUPABASE_URL || "",
  SUPABASE_ANON_KEY: env.VITE_SUPABASE_ANON_KEY || "",
  UNIMATE_API_URL: env.VITE_UNIMATE_API_URL || env.UNIMATE_API_URL || "http://localhost:8080",
  COMPANION_DEBUG:
    process.argv.includes("--debug") || String(env.VITE_COMPANION_DEBUG).toLowerCase() === "true",
};

const missing = Object.entries(config)
  .filter(([key, value]) => !["UNIMATE_API_URL", "COMPANION_DEBUG"].includes(key) && !value)
  .map(([key]) => key);
// This output is loaded by a browser extension, including during unpacked
// development. Reject privileged keys here, not only at Store packaging time.
const validPublicKey = (() => {
  const key = config.SUPABASE_ANON_KEY;
  if (/YOUR_|PLACEHOLDER/i.test(key)) return false;
  if (/^sb_publishable_[A-Za-z0-9_-]+$/.test(key)) return true;
  const parts = key.split(".");
  if (parts.length !== 3 || parts.some((part) => !/^[A-Za-z0-9_-]+$/.test(part))) return false;
  try {
    // This verifies key category, not signature or whether the key is active.
    return JSON.parse(Buffer.from(parts[1], "base64url").toString("utf8"))?.role === "anon";
  } catch {
    return false;
  }
})();
if (missing.length) {
  console.error(`Missing ${missing.join(", ")} in .env.local.`);
  process.exitCode = 1;
} else if (!validPublicKey) {
  console.error(
    "Companion requires a public Supabase publishable key or legacy anon key. Server-only keys must never be written to browser configuration.",
  );
  process.exitCode = 1;
} else if (
  !isPublicCompanionOrigin(config.SUPABASE_URL) ||
  !isDevelopmentCompanionOrigin(config.UNIMATE_API_URL)
) {
  console.error(
    "Companion URLs must be public HTTPS origins without credentials, ports, paths, queries, or fragments; localhost HTTP is allowed only for development.",
  );
  process.exitCode = 1;
} else {
  config.SUPABASE_URL = new URL(config.SUPABASE_URL).origin;
  config.UNIMATE_API_URL = new URL(config.UNIMATE_API_URL).origin;
  fs.writeFileSync(
    outputPath,
    `// Generated by npm run companion:configure. Public client configuration only.
self.UNIMATE_COMPANION_CONFIG = {
  SUPABASE_URL: ${JSON.stringify(config.SUPABASE_URL)},
  SUPABASE_ANON_KEY: ${JSON.stringify(config.SUPABASE_ANON_KEY)},
  UNIMATE_API_URL: ${JSON.stringify(config.UNIMATE_API_URL)},
  COMPANION_DEBUG: ${JSON.stringify(config.COMPANION_DEBUG)},
};
`,
  );
  console.log(`Configured ${path.relative(root, outputPath)}.`);
}
