import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const envPath = path.join(root, ".env.local");
const outputPath = path.join(root, "browser-companion", "config.local.js");

function parseEnv(text) {
  const values = {};
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const match = line.match(/^(?:export\s+)?([A-Z0-9_]+)\s*=\s*(.*)$/);
    if (!match) continue;
    let value = match[2].trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    values[match[1]] = value;
  }
  return values;
}

const env = fs.existsSync(envPath) ? parseEnv(fs.readFileSync(envPath, "utf8")) : process.env;
const config = {
  SUPABASE_URL: env.VITE_SUPABASE_URL || "",
  SUPABASE_ANON_KEY: env.VITE_SUPABASE_ANON_KEY || "",
  UNIMATE_API_URL: env.VITE_UNIMATE_API_URL || env.UNIMATE_API_URL || "http://localhost:8080",
  COMPANION_DEBUG:
    process.argv.includes("--debug") || String(env.VITE_COMPANION_DEBUG).toLowerCase() === "true",
};

const missing = Object.entries(config)
  .filter(([key, value]) => key !== "UNIMATE_API_URL" && !value)
  .map(([key]) => key);
if (missing.length) {
  console.error(`Missing ${missing.join(", ")} in .env.local.`);
  process.exitCode = 1;
} else {
  fs.writeFileSync(
    outputPath,
    `// Generated by npm run companion:configure. Public client configuration only.
self.UNIMATE_COMPANION_CONFIG = {
  SUPABASE_URL: ${JSON.stringify(config.SUPABASE_URL)},
  SUPABASE_ANON_KEY: ${JSON.stringify(config.SUPABASE_ANON_KEY)},
  UNIMATE_API_URL: ${JSON.stringify(config.UNIMATE_API_URL)},
  COMPANION_DEBUG: ${JSON.stringify(config.COMPANION_DEBUG)},
};
`,
  );
  console.log(`Configured ${path.relative(root, outputPath)}.`);
}
